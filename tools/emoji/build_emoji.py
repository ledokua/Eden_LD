#!/usr/bin/env python3
"""
Rebuilds Eden_LD's standard emoji data (run when Discord/Twemoji add emojis):

  src/main/resources/eden_ld_emoji/unicode_emoji.tsv   the list (order = character order)
  src/main/resources/eden_ld_emoji/sheets/NN.png       Twemoji at 32 px, 256 per sheet
                                                       (16 x 16 cells, in list order)

Sources: emojibase-data (MIT) for the list, categories and Discord-style (JoyPixels) names;
Twemoji (CC-BY 4.0, jdecked fork) for the images. Needs Python 3 + Pillow and network access.

Usage: python3 tools/emoji/build_emoji.py [work-dir]
"""
import io, json, os, sys, urllib.request
from concurrent.futures import ThreadPoolExecutor
from PIL import Image

EMOJIBASE = "https://cdn.jsdelivr.net/npm/emojibase-data@17.0.0/en/"
TWEMOJI = "https://cdn.jsdelivr.net/gh/jdecked/twemoji@17.0.3/assets/72x72/"
ROOT = os.path.normpath(os.path.join(os.path.dirname(__file__), "..", ".."))
OUT = os.path.join(ROOT, "src", "main", "resources", "eden_ld_emoji")
CELL, GRID = 32, 16  # 32 px emojis, 16 x 16 per sheet

work = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "build", "emoji-work")
os.makedirs(os.path.join(work, "72"), exist_ok=True)

def fetch(url):
    with urllib.request.urlopen(url, timeout=30) as response:
        return response.read()

def data(name):
    path = os.path.join(work, name.replace("/", "_"))
    if not os.path.exists(path):
        open(path, "wb").write(fetch(EMOJIBASE + name))
    return json.load(open(path, encoding="utf-8"))

emojis, joypixels, emojibase = data("data.json"), data("shortcodes/joypixels.json"), data("shortcodes/emojibase.json")

def as_list(value):
    return [] if value is None else value if isinstance(value, list) else [value]

used = set()
def names(hexcode):
    out = []
    for name in as_list(joypixels.get(hexcode)) or as_list(emojibase.get(hexcode)):
        name = name.replace("-", "_")
        if name.lower() not in used:
            used.add(name.lower())
            out.append(name)
    return out

rows = []  # (hexcode, group, flags, names)
for emoji in sorted(emojis, key=lambda e: e.get("order", 10 ** 9)):
    group = emoji.get("group")
    if group is None or group == 2:  # regional letters alone, skin-tone swatches
        continue
    base = names(emoji["hexcode"])
    if not base:
        continue
    rows.append((emoji["hexcode"], group, "t" if emoji.get("type") == 0 else "", base))
    for skin in emoji.get("skins") or []:
        skin_names = names(skin["hexcode"])
        if skin_names:
            rows.append((skin["hexcode"], group, "s", skin_names))

def twemoji_files(hexcode):
    """Twemoji's file name (with fallbacks — it isn't fully consistent about FE0F)."""
    parts = [p.lower().lstrip("0") or "0" for p in hexcode.split("-")]
    keep = "-".join(parts) if "200d" in parts else "-".join(p for p in parts if p != "fe0f")
    return [keep, "-".join(p for p in parts if p != "fe0f")]

def image(hexcode):
    for name in twemoji_files(hexcode):
        path = os.path.join(work, "72", name + ".png")
        if not os.path.exists(path):
            try:
                open(path, "wb").write(fetch(TWEMOJI + name + ".png"))
            except Exception:
                continue
        return Image.open(path).convert("RGBA").resize((CELL, CELL), Image.BOX)
    return None

with ThreadPoolExecutor(8) as pool:
    images = list(pool.map(lambda row: image(row[0]), rows))
missing = [row[0] for row, im in zip(rows, images) if im is None]

lines = ["# Eden_LD standard emojis (generated by tools/emoji/build_emoji.py): emojibase-data 17.0.0 (MIT),",
         "# names as on Discord (JoyPixels shortcodes; emojibase for the newest). Images: Twemoji 17 (CC-BY 4.0),",
         "# in sheets/NN.png, 16 x 16 cells of 32 px in this order. hexcode <TAB> group <TAB> flags (t = text-style,",
         "# s = skin tone) <TAB> names"]
lines += [f"{h}\t{g}\t{f}\t{','.join(n)}" for h, g, f, n in rows]
open(os.path.join(OUT, "unicode_emoji.tsv"), "w", encoding="utf-8").write("\n".join(lines) + "\n")

sheets = os.path.join(OUT, "sheets")
os.makedirs(sheets, exist_ok=True)
for old in os.listdir(sheets):
    os.remove(os.path.join(sheets, old))
per_sheet = GRID * GRID
total = 0
for start in range(0, len(rows), per_sheet):
    count = min(per_sheet, len(rows) - start)
    sheet = Image.new("RGBA", (GRID * CELL, ((count + GRID - 1) // GRID) * CELL), (0, 0, 0, 0))
    for i in range(count):
        if images[start + i] is not None:
            sheet.paste(images[start + i], ((i % GRID) * CELL, (i // GRID) * CELL))
    path = os.path.join(sheets, f"{start // per_sheet:02d}.png")
    sheet.save(path, optimize=True)
    total += os.path.getsize(path)
print(f"{len(rows)} emojis, {(len(rows) + per_sheet - 1) // per_sheet} sheets, {total / 1048576:.2f} MB; "
      f"no image for: {missing or 'none'}")
